# Programa: Convertir tipos de datos

numero_cadena = "25"

# Convertir la cadena a un entero
numero_entero = int(numero_cadena)
print(f"Cadena: {numero_cadena}")
print(f"Entero: {numero_entero}")

# Convertir el entero a flotante
numero_decimal = float(numero_entero)
print(f"Decimal: {numero_decimal}")

# Convetir el floante a cadena nuevamente
numero_texto = str(numero_decimal)
print(f"Texto: {numero_texto}")